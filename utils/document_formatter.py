import io
import re

from datetime import datetime

from pathlib import Path

from typing import Optional

from docx import Document

from docx.enum.text import WD_ALIGN_PARAGRAPH

from docx.shared import Inches, Pt

from fpdf import FPDF

from utils.text_utils import sanitize_text


def _split_sections(text: str):

    clean = sanitize_text(text)

    return [
        part.strip()

        for part in re.split(
            r"\n\s*\n",
            clean
        )

        if part.strip()
    ]


def format_txt(text: str) -> bytes:

    return sanitize_text(text).encode(
        "utf-8"
    )


def format_docx(
    text: str,
    doc_type: str,
    logo_path: Optional[str] = None
) -> bytes:

    document = Document()

    section = document.sections[0]

    section.top_margin = Inches(0.7)

    section.bottom_margin = Inches(0.7)

    section.left_margin = Inches(0.8)

    section.right_margin = Inches(0.8)


    styles = document.styles

    styles["Normal"].font.name = (
        "Times New Roman"
    )

    styles["Normal"].font.size = Pt(11)


    # Logo

    if (
        logo_path
        and Path(logo_path).exists()
    ):

        paragraph = document.add_paragraph()

        paragraph.alignment = (
            WD_ALIGN_PARAGRAPH.CENTER
        )

        paragraph.add_run().add_picture(

            logo_path,

            width=Inches(1.1)
        )


    # Title

    title = document.add_paragraph()

    title.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    run = title.add_run(
        doc_type.upper()
    )

    run.bold = True

    run.font.name = "Times New Roman"

    run.font.size = Pt(16)


    # Date

    generated = document.add_paragraph()

    generated.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    date_run = generated.add_run(

        "Generated by LegalEase • "
        + datetime.now().strftime(
            "%Y-%m-%d"
        )
    )

    date_run.italic = True


    # Content

    for block in _split_sections(text):

        lines = block.splitlines()

        first_line = lines[0].strip()


        is_heading = (

            len(lines) == 1

            and len(first_line) < 120

            and (

                first_line.isupper()

                or re.match(
                    r"^\d+[\.\)]\s+",
                    first_line
                )

                or first_line.lower().startswith(
                    (
                        "draft notice",
                        "parties",
                        "definitions",
                        "purpose",
                        "signatures",
                        "signature",
                        "general provisions"
                    )
                )
            )
        )


        if is_heading:

            paragraph = document.add_paragraph()

            heading = paragraph.add_run(
                first_line
            )

            heading.bold = True

            heading.font.name = (
                "Times New Roman"
            )

            heading.font.size = Pt(12)

        else:

            for line in lines:

                paragraph = document.add_paragraph()

                paragraph.paragraph_format.space_after = (
                    Pt(6)
                )

                paragraph.add_run(line)


    # Footer

    footer = section.footer.paragraphs[0]

    footer.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    footer_run = footer.add_run(

        "LegalEase — AI-generated draft. "
        "Review for applicable law before use."
    )

    footer_run.font.size = Pt(8)


    stream = io.BytesIO()

    document.save(stream)

    return stream.getvalue()


class LegalEasePDF(FPDF):

    def _init_(
        self,
        doc_type: str,
        logo_path: Optional[str] = None
    ):

        super()._init_()

        self.doc_type = doc_type

        self.logo_path = logo_path


    def header(self):

        if (
            self.logo_path
            and Path(self.logo_path).exists()
        ):

            try:

                self.image(
                    self.logo_path,
                    x=92,
                    y=8,
                    w=26
                )

                self.ln(20)

            except Exception:

                self.ln(4)

        else:

            self.ln(4)


        self.set_font(
            "Helvetica",
            "B",
            14
        )

        self.cell(
            0,
            8,
            self.doc_type.upper(),
            align="C"
        )

        self.ln(12)


    def footer(self):

        self.set_y(-15)

        self.set_font(
            "Helvetica",
            size=7
        )

        self.cell(

            0,
            8,

            "LegalEase — AI-generated draft. "
            "Review for applicable law before use.",

            align="C"
        )


def format_pdf(
    text: str,
    doc_type: str,
    logo_path: Optional[str] = None
) -> bytes:

    pdf = LegalEasePDF(
        doc_type=doc_type,
        logo_path=logo_path
    )

    pdf.set_auto_page_break(
        auto=True,
        margin=18
    )

    pdf.add_page()

    pdf.set_font(
        "Helvetica",
        size=10
    )


    for block in _split_sections(text):

        lines = block.splitlines()

        first_line = lines[0].strip()


        is_heading = (

            len(lines) == 1

            and len(first_line) < 120

            and (

                first_line.isupper()

                or re.match(
                    r"^\d+[\.\)]\s+",
                    first_line
                )

                or first_line.lower().startswith(
                    (
                        "draft notice",
                        "parties",
                        "definitions",
                        "purpose",
                        "signatures",
                        "signature",
                        "general provisions"
                    )
                )
            )
        )


        if is_heading:

            pdf.set_font(
                "Helvetica",
                "B",
                11
            )

            pdf.multi_cell(
                0,
                6,
                first_line
            )

            pdf.ln(2)

            pdf.set_font(
                "Helvetica",
                size=10
            )

        else:

            for line in lines:

                pdf.multi_cell(
                    0,
                    5.5,
                    line
                )

            pdf.ln(2)


    return bytes(
        pdf.output()
    )